/* Generates supabase/seed.sql from the current i18n dictionary, so the database
   starts out holding exactly the content the static pages already show.
   Run:  node tools/make_seed.js                                              */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
global.window = {};
eval(fs.readFileSync(path.join(ROOT, "assets/js/i18n.js"), "utf8"));
const EN = window.I18N.en, TH = window.I18N.th;

const q = (v) => v === null || v === undefined ? "null" : "'" + String(v).replace(/'/g, "''") + "'";
const out = [];

out.push("-- Generated by tools/make_seed.js — เนื้อหาเริ่มต้นของเว็บ");
out.push("-- รันหลัง schema.sql (รันซ้ำได้: ล้างของเดิมแล้วใส่ใหม่)\n");

/* ---------- lessons ---------- */
const LESSONS = [
  ["v1", "beginner",     "groove",    "14:52"],
  ["v2", "beginner",     "technique", "11:08"],
  ["v3", "beginner",     "reading",   "16:30"],
  ["v4", "intermediate", "groove",    "18:24"],
  ["v5", "intermediate", "technique", "12:40"],
  ["v6", "intermediate", "technique", "21:15"],
  ["v7", "advanced",     "groove",    "24:05"],
  ["v8", "advanced",     "reading",   "19:47"],
  ["v9", "advanced",     "groove",    "27:12"],
];
out.push("delete from public.site_lessons;");
out.push("insert into public.site_lessons (sort, level, category, duration, title_en, title_th, desc_en, desc_th) values");
out.push(LESSONS.map(([k, lvl, cat, dur], i) =>
  `  (${(i + 1) * 10}, ${q(lvl)}, ${q(cat)}, ${q(dur)}, ${q(EN["ls." + k + "t"])}, ${q(TH["ls." + k + "t"])}, ${q(EN["ls." + k + "d"])}, ${q(TH["ls." + k + "d"])})`
).join(",\n") + ";\n");

/* ---------- packages ---------- */
const PACKS = [
  [10, "1 Lesson",   EN["pm.r1s"], TH["pm.r1s"], "1,000฿", "",          "",              "",              false],
  [20, "8 Lessons",  EN["pm.r2s"], TH["pm.r2s"], "7,600฿", "8,000฿",   EN["pm.save400"],  TH["pm.save400"],  false],
  [30, "10 Lessons", EN["pm.r3s"], TH["pm.r3s"], "9,000฿", "10,000฿",  EN["pm.save1000"], TH["pm.save1000"], true],
];
out.push("delete from public.site_packages;");
out.push("insert into public.site_packages (sort, name, sub_en, sub_th, price, price_was, save_en, save_th, is_best) values");
out.push(PACKS.map(r =>
  `  (${r[0]}, ${q(r[1])}, ${q(r[2])}, ${q(r[3])}, ${q(r[4])}, ${q(r[5])}, ${q(r[6])}, ${q(r[7])}, ${r[8]})`
).join(",\n") + ";\n");

/* ---------- faq ---------- */
out.push("delete from public.site_faq;");
out.push("insert into public.site_faq (sort, q_en, q_th, a_en, a_th) values");
out.push([1, 2, 3, 4, 5].map(n =>
  `  (${n * 10}, ${q(EN["ct.q" + n])}, ${q(TH["ct.q" + n])}, ${q(EN["ct.a" + n])}, ${q(TH["ct.a" + n])})`
).join(",\n") + ";\n");

/* ---------- testimonials ---------- */
out.push("delete from public.site_testimonials;");
out.push("insert into public.site_testimonials (sort, person, role_en, role_th, quote_en, quote_th) values");
out.push([1, 2, 3].map(n =>
  `  (${n * 10}, ${q(EN["tm." + n + "n"])}, ${q(EN["tm." + n + "r"])}, ${q(TH["tm." + n + "r"])}, ${q(EN["tm." + n])}, ${q(TH["tm." + n])})`
).join(",\n") + ";\n");

/* ---------- timeline ---------- */
out.push("delete from public.site_timeline;");
out.push("insert into public.site_timeline (sort, year, title_en, title_th, desc_en, desc_th) values");
out.push([1, 2, 3, 4, 5].map(n =>
  `  (${n * 10}, ${q((EN["pf.t" + n + "y"] || "").split("—")[0].trim())}, ${q(EN["pf.t" + n + "t"])}, ${q(TH["pf.t" + n + "t"])}, ${q(EN["pf.t" + n + "d"])}, ${q(TH["pf.t" + n + "d"])})`
).join(",\n") + ";\n");

/* ---------- settings ---------- */
const SETTINGS = [
  ["hero_eyebrow",   "หน้าแรก · บรรทัดบนสุด",      EN["hero.eyebrow"], TH["hero.eyebrow"]],
  ["hero_role",      "หน้าแรก · บรรทัดตำแหน่ง",     EN["hero.role"],    TH["hero.role"]],
  ["hero_text",      "หน้าแรก · ย่อหน้าแนะนำ",      EN["hero.text"],    TH["hero.text"]],
  ["about_p1",       "หน้าแรก · แนะนำตัว ย่อหน้า 1", EN["ap.p1"],        TH["ap.p1"]],
  ["about_p2",       "หน้าแรก · แนะนำตัว ย่อหน้า 2", EN["ap.p2"],        TH["ap.p2"]],
  ["profile_bio_1",  "ประวัติ · ย่อหน้า 1",         EN["pf.b1"],        TH["pf.b1"]],
  ["profile_bio_2",  "ประวัติ · ย่อหน้า 2",         EN["pf.b2"],        TH["pf.b2"]],
  ["profile_bio_3",  "ประวัติ · ย่อหน้า 3",         EN["pf.b3"],        TH["pf.b3"]],
  ["promo_lead",     "บทเรียน · คำโปรยเหนือราคา",   EN["pm.lead"],      TH["pm.lead"]],
  ["promo_note",     "บทเรียน · หมายเหตุใต้ราคา",   EN["pm.note"],      TH["pm.note"]],
  ["contact_email",  "อีเมลติดต่อ",                "hello@suttipojdrums.com", "hello@suttipojdrums.com"],
  ["contact_phone",  "เบอร์โทร",                   "+66 2 000 0000",          "+66 2 000 0000"],
  ["contact_hours",  "เวลาทำการ",                  EN["ct.i3v"],       TH["ct.i3v"]],
  ["contact_place",  "สถานที่",                    EN["ct.i2v"],       TH["ct.i2v"]],
];
out.push("insert into public.site_settings (key, label, value_en, value_th) values");
out.push(SETTINGS.map(r => `  (${q(r[0])}, ${q(r[1])}, ${q(r[2])}, ${q(r[3])})`).join(",\n"));
out.push("on conflict (key) do update set label = excluded.label,\n" +
         "  value_en = excluded.value_en, value_th = excluded.value_th, updated_at = now();\n");

const dest = path.join(ROOT, "supabase", "seed.sql");
fs.writeFileSync(dest, out.join("\n"));
console.log("wrote", dest, fs.statSync(dest).size, "bytes");
